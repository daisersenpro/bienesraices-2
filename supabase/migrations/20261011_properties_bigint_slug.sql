alter table public.properties
  add column if not exists id_new bigint generated by default as identity;

with numbered_properties as (
  select id, row_number() over (order by created_at, slug) as new_id
  from public.properties
)
update public.properties as properties
set id_new = numbered_properties.new_id
from numbered_properties
where properties.id = numbered_properties.id;

alter table public.properties
  drop constraint if exists properties_pkey;

alter table public.properties
  drop column id;

alter table public.properties
  rename column id_new to id;

alter table public.properties
  add primary key (id);

alter table public.properties
  alter column id set generated by default;

select setval(
  pg_get_serial_sequence('public.properties', 'id'),
  coalesce((select max(id) from public.properties), 1),
  true
);
